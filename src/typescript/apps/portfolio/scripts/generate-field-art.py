"""Build the schematic field geometry and matching identity assets (stdlib only).

Run from the portfolio directory: python scripts/generate-field-art.py
These are illustrative Gaussian fields, not fitted economic observations.
The browser animates two SVG groups; it never evaluates the field.
"""

