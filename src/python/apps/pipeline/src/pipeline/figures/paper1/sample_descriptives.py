r"""Paper 1 sample-descriptives exhibits: the per-sector table and its bindings.

``render-paper1-sample-descriptives`` reads the ``compute-sample-descriptives``
results and writes a self-contained booktabs fragment that the manuscript
``\\input``\\ s. Every number is formatted directly, to a fixed stated
precision, from the results file, and undefined/sparse-sector statistics render
as an explicit em dash (``\\textemdash``) rather than a fabricated ``0.00``.
The complete ticker roster is rendered by the shared
``render-sample-universe-table`` command because it does not fit a page as a
float. Paper 5 reuses :func:`render_sample_descriptives_table` with its own
caption, label, and generator.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any, cast

from pipeline.figures._latex import escape_latex
from pipeline.figures.paper1._format import fmt, fmt_int
from pipeline.io.values import Blank, Comment, PublicationValue

if TYPE_CHECKING:
    from pipeline.io.values import Record


def _sector_row(sector: str, row: dict[str, object]) -> str:
    cells = [
        escape_latex(sector),
        fmt_int(row["n_firms"]),
        fmt(row["mean_articles_per_firm"], 1),
        fmt(row.get("mean_daily_return_volatility"), 4),
        fmt(row.get("mean_within_sector_w2_distance"), 3),
        fmt(row.get("mean_cross_sector_w2_distance"), 3),
    ]
    return " & ".join(cells) + r" \\"


def render_sector_table(summary: dict[str, object]) -> str:
    """Format sector and overall sample statistics from saved results."""
    sectors = cast("dict[str, dict[str, object]]", summary["sectors"])
    overall = cast("dict[str, object]", summary["overall"])

    lines = [
        r"\small",
        r"\begin{tabularx}{\linewidth}{Xrrrrr}",
        r"\toprule",
        (
            r"Sector & $n$ & Articles & Volatility & "
            r"$W_2$ within & $W_2$ cross \\"
        ),
        r"\midrule",
    ]
    lines.extend(_sector_row(sector, sectors[sector]) for sector in sorted(sectors))
    lines.extend(
        (
            r"\midrule",
            _sector_row(
                "All sectors",
                {
                    "n_firms": overall["n_firms"],
                    "mean_articles_per_firm": overall["mean_articles_per_firm"],
                    "mean_daily_return_volatility": overall.get(
                        "mean_daily_return_volatility"
                    ),
                    "mean_within_sector_w2_distance": overall.get(
                        "mean_within_sector_w2_distance"
                    ),
                    "mean_cross_sector_w2_distance": overall.get(
                        "mean_cross_sector_w2_distance"
                    ),
                },
            ),
        )
    )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabularx}")
    return "\n".join(lines)


_PAPER1_CAPTION = (
    r"Per-sector sample composition: firm count, mean article "
    r"count per firm, mean daily return volatility, and mean within- "
    r"versus cross-sector pairwise rooted $W_2$ distance. Articles are "
    r"subsampled to a fixed per-firm cap, so counts are near-constant "
    r"by construction. A dash indicates a statistic that is undefined "
    r"for that sector (e.g.\ within-sector distance for a singleton "
    r"sector)."
)


def render_sample_descriptives_table(
    summary_file: Path,
    output_file: Path,
    *,
    caption: str = _PAPER1_CAPTION,
    label: str = "tab:sample-descriptives-sectors",
    generator: str = "pipeline render-paper1-sample-descriptives",
) -> str:
    """Render the sample-descriptives fragment from ``summary_file``.

    Write it to ``output_file`` and return the fragment text.

    Volatility is displayed to 4 decimal places (daily scale, matching the
    ``units`` documentation in the results file — not annualised). Article
    counts to 1 decimal place (means/medians over integer counts). W2
    distances to 3 decimal places, matching the precision used elsewhere in
    Paper 1's generated numbers for this quantity.

    ``caption``, ``label`` and ``generator`` are parameters because Papers 1
    and 5 tabulate the same statistics over different encoders and must not
    share a float label or claim the same producer. The defaults reproduce
    Paper 1's fragment byte for byte.
    """
    summary = json.loads(Path(summary_file).read_text(encoding="utf-8"))

    sector_table = render_sector_table(summary)
    sector_caption = rf"\caption{{{caption}}}"
    fragment = (
        f"% AUTO-GENERATED by {generator} -- do not edit by hand.\n\n"
        r"\begin{table}[H]"
        "\n\n"
        r"\centering"
        f"\n\n{sector_table}\n\n{sector_caption}\n\n"
        rf"\label{{{label}}}"
        "\n\n"
        r"\end{table}"
    )
    fragment += "\n"

    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(fragment, encoding="utf-8")
    return fragment


def append_sample_descriptives_records(
    records: list[Record], sample_descriptives: dict[str, Any] | None
) -> None:
    """Append the shared sample statistics to publication bindings."""
    if sample_descriptives:
        overall = sample_descriptives.get("overall", {}) or {}
        records += [
            Blank(),
            Comment(
                "--- Sample descriptives, pooled/overall "
                "(data/shared/sample_descriptives/results.json) ---"
            ),
            PublicationValue(
                "sample-desc-articles-per-firm",
                float(overall["mean_articles_per_firm"]),
            ),
            PublicationValue(
                "sample-desc-total-articles", int(overall.get("total_articles", 0))
            ),
        ]
