def simplify(points, tolerance=.25):
    """Preserve subpixel accuracy without shipping the full sampling grid."""
    if len(points) < 3:
        return points
    a, b = points[0], points[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = math.hypot(dx, dy)
    distances = [(abs(dy * (p[0] - a[0]) - dx * (p[1] - a[1])) / length
                  if length else math.dist(a, p)) for p in points[1:-1]]
    maximum = max(distances)
    if maximum <= tolerance:
        return [a, b]
    index = distances.index(maximum) + 1
    return simplify(points[:index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def field(x, y):
    # Two economic regions joined by a broad, low-frequency mode.
    u, v = (x - 320) / 175, (y - 306) / 175
    return (math.exp(-((u + .52) ** 2 / .57 + (v + .42) ** 2 / .9))
            + .88 * math.exp(-((u - .64) ** 2 / .65 + (v - .65) ** 2 / .44)))


def contour(level):
    segments = []
    step = 6
    for y in range(30, 582, step):
        for x in range(26, 614, step):
            points = [(x, y), (x + step, y), (x + step, y + step), (x, y + step)]
            values = [field(*p) for p in points]
            hits = []
            for i in range(4):
                j = (i + 1) % 4
                if (values[i] < level) != (values[j] < level):
                    t = (level - values[i]) / (values[j] - values[i])
                    hits.append(tuple(round(points[i][k] + t * (points[j][k] - points[i][k]), 2) for k in (0, 1)))
            if len(hits) == 2:
                segments.append(hits)
    neighbours = {}
    for a, b in segments:
        neighbours.setdefault(a, []).append(b)
        neighbours.setdefault(b, []).append(a)
    paths = []
    while neighbours:
        start = next((p for p, n in neighbours.items() if len(n) == 1), next(iter(neighbours)))
        current, chain = start, [start]
        while current in neighbours and neighbours[current]:
            target = neighbours[current].pop()
            if not neighbours[current]:
                del neighbours[current]
            neighbours[target].remove(current)
            if not neighbours[target]:
                del neighbours[target]
            chain.append(target)
            current = target
        # Keep the sampled curves precise and avoid excessive SVG precision.
        d = "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in simplify(chain))
        if chain[-1] == chain[0]:
            d += "Z"
        paths.append(d)
    return " ".join(paths)


