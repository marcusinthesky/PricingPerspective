"""Paper 1 original-W2 sector diagnostic and publication bindings."""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, cast

from pipeline.figures._latex import escape_latex
from pipeline.figures.paper1._format import fmt, fmt_int, opt_float
from pipeline.io.values import Blank, Comment, PublicationValue
from pipeline.io.w2_permanova_artifacts import read_w2_permanova_results

if TYPE_CHECKING:
    from pathlib import Path

    from pipeline.io.values import Record


@dataclass(frozen=True, slots=True)
class Paper1W2PermanovaRenderPaths:
    """Saved sector-test results and the generated table destination."""

    results_file: Path
    output_dir: Path


def render_paper1_w2_permanova(paths: Paper1W2PermanovaRenderPaths) -> None:
    """Render the sector diagnostic from saved results without recomputation."""
    summary = read_w2_permanova_results(paths.results_file)
    paths.output_dir.mkdir(parents=True, exist_ok=True)
    (paths.output_dir / "w2_permanova.tex").write_text(
        render_w2_permanova_table(summary), encoding="utf-8"
    )


def render_w2_permanova_table(summary: dict[str, Any]) -> str:
    """Describe the decomposition, random-label reference, and spread companion."""
    test = summary["permanova"]
    dispersion = summary["dispersion"]
    sector_sizes = cast("dict[str, object]", summary["sector_sizes"])
    sector_text = ", ".join(
        f"{escape_latex(name)}={fmt_int(count)}"
        for name, count in sorted(sector_sizes.items())
    )
    exclusions = ", ".join(
        escape_latex(name) for name in dispersion["excluded_singleton_sectors"]
    )
    dispersion_scope = (
        "The spread companion retains "
        + fmt_int(dispersion["n_firms"])
        + " firms in "
        + fmt_int(dispersion["n_groups"])
        + " replicated sectors"
        + ("; excluded singleton sectors are " + exclusions if exclusions else "")
        + ". "
    )
    if dispersion["status"] == "computed":
        dispersion_detail = (
            r"It uses all positive principal-coordinate axes, within-sector "
            r"spatial medians, the $\sqrt{n_g/(n_g-1)}$ radius adjustment, and "
            + fmt_int(dispersion["n_permutations"])
            + r" residual permutations of the scalar sector model. A large "
            r"dispersion $p$-value does not establish equal sector spreads."
        )
    else:
        dispersion_detail = (
            "The spread companion was not computed: "
            + escape_latex(str(dispersion["reason"]).replace("_", " "))
            + "."
        )
    caption = (
        r"\caption{One-way PERMANOVA on the canonical rooted W$_2$ matrix for "
        + fmt_int(summary["n_firms"])
        + " firms in "
        + fmt_int(summary["n_groups"])
        + r" sectors. Sums of squares use squared original W$_2$ distances, "
        r"without projecting or estimating Wasserstein barycentres. The "
        r"reference distribution uses "
        + fmt_int(test["n_permutations"])
        + r" whole-firm label permutations preserving sector sizes, and "
        r"add-one upper-tail $p$-values. The analytic random-label expectation "
        r"is $(K-1)/(N-1)$; excess $R^2$ subtracts the simulated null mean. "
        r"These are descriptive null references, not confidence intervals or "
        r"causal sector effects; permutation inference requires exchangeability "
        r"under the reference null. "
        + (
            "The main test was not computed: "
            + escape_latex(str(test["reason"]).replace("_", " "))
            + ". "
            if test["status"] != "computed"
            else ""
        )
        + dispersion_scope
        + dispersion_detail
        + " Sector sizes are "
        + sector_text
        + r".}"
    )
    return "\n".join(
        [
            (
                "% AUTO-GENERATED by pipeline render-paper1-w2-permanova "
                "-- do not edit by hand."
            ),
            r"\begin{table}[H]",
            r"\centering",
            r"\small",
            r"\textit{Panel A: original-distance sector decomposition}",
            r"\par\smallskip",
            r"\begin{tabular}{rrrrrr}",
            r"\toprule",
            r"$SS_W$ & $SS_B$ & $SS_T$ & $R^2$ & $F_{\rm pseudo}$ & $p_{\rm perm}$ \\",
            r"\midrule",
            " & ".join(
                (
                    r"$\infty$"
                    if key == "pseudo_f"
                    and test["pseudo_f_status"] == "positive_infinity"
                    else fmt(test[key], precision)
                )
                for key, precision in (
                    ("ss_within", 3),
                    ("ss_between", 3),
                    ("ss_total", 3),
                    ("r2", 3),
                    ("pseudo_f", 3),
                    ("pvalue", 4),
                )
            )
            + r" \\",
            r"\bottomrule",
            r"\end{tabular}",
            r"\par\medskip",
            r"\textit{Panel B: random-label reference}",
            r"\par\smallskip",
            r"\begin{tabular}{rrr}",
            r"\toprule",
            r"$\mathbb{E}_{\rm perm}[R^2]$ & Mean permuted $R^2$ & Excess $R^2$ \\",
            r"\midrule",
            " & ".join(
                fmt(test[key], 3)
                for key in ("null_r2_expectation", "null_r2_mean", "excess_r2")
            )
            + r" \\",
            r"\bottomrule",
            r"\end{tabular}",
            r"\par\medskip",
            r"\textit{Panel C: dispersion companion}",
            r"\par\smallskip",
            r"\begin{tabular}{rrrr}",
            r"\toprule",
            r"Firms & Sectors & $F_{\rm disp}$ & $p_{\rm disp}$ \\",
            r"\midrule",
            " & ".join(
                [
                    fmt_int(dispersion["n_firms"]),
                    fmt_int(dispersion["n_groups"]),
                    (
                        r"$\infty$"
                        if dispersion["statistic_status"] == "positive_infinity"
                        else fmt(dispersion["statistic"], 3)
                    ),
                    fmt(dispersion["pvalue"], 4),
                ]
            )
            + r" \\",
            r"\bottomrule",
            r"\end{tabular}",
            caption,
            r"\label{tab:w2-permanova}",
            r"\end{table}",
            "",
        ]
    )


def append_w2_permanova_records(
    records: list[Record], summary: dict[str, Any] | None
) -> None:
    """Bind saved W2 diagnostic values, preserving undefined statistics."""
    if not summary:
        return
    test = summary["permanova"]
    dispersion = summary["dispersion"]
    records += [
        Blank(),
        Comment("--- Original-W2 sector PERMANOVA and dispersion companion ---"),
        Comment("Source: data/papers/paper1/w2_permanova/results.json"),
        PublicationValue("w2-permanova-n-firms", int(summary["n_firms"])),
        PublicationValue("w2-permanova-n-groups", int(summary["n_groups"])),
        *(
            PublicationValue("w2-permanova-" + name, opt_float(test[key]))
            for name, key in (
                ("r2", "r2"),
                ("f", "pseudo_f"),
                ("p", "pvalue"),
                ("null-r2", "null_r2_expectation"),
                ("excess-r2", "excess_r2"),
            )
        ),
        PublicationValue("w2-permanova-dispersion-p", opt_float(dispersion["pvalue"])),
    ]
