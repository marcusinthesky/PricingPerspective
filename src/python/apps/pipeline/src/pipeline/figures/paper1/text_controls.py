"""Publication table and scalar bindings for the saved text comparisons."""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any

from pipeline.figures.paper1._format import fmt
from pipeline.figures.shared_tables import _render_longtable
from pipeline.io.values import PublicationValue

if TYPE_CHECKING:
    from pathlib import Path

    from pipeline.io.values import Record

_LABELS = {
    "canonical_qwen8b_w2": r"Qwen3-8B $W_2$ (reference)",
    "tfidf_firm_cosine": "TF--IDF firm cosine distance",
    "tfidf_document_w2": r"TF--IDF document $W_2$",
    "MLMvsCLM/610m-clm-42k": r"610M CLM $W_2$",
    "MLMvsCLM/610m-mlm30-42k": r"610M MLM30 $W_2$",
    "MLMvsCLM/610m-mlm40-42k": r"610M MLM40 $W_2$",
    "MLMvsCLM/610m-mlm50-42k": r"610M MLM50 $W_2$",
}


def append_text_controls_records(
    records: list[Record], summary: dict[str, Any] | None
) -> None:
    """Bind the lexical-distribution fit used in the main results paragraph."""
    if not summary:
        return
    cell = next(row for row in summary["cells"] if row["arm"] == "tfidf_document_w2")
    records.append(
        PublicationValue("text-controls-tfidf-document-partial-r2", cell["partial_r2"])
    )


def render_paper1_text_controls(results_file: Path, output_dir: Path) -> None:
    """Publish saved estimates without recomputing representations or inference."""
    summary = json.loads(results_file.read_text(encoding="utf-8"))
    rows: list[str] = []
    for pretraining, title in (
        (False, "Panel A: lexical benchmarks and canonical reference"),
        (True, "Panel B: pretraining checkpoints"),
    ):
        rows.append(rf"\multicolumn{{4}}{{l}}{{\textit{{{title}}}}} \\")
        for cell in summary["cells"]:
            arm = cell["arm"]
            if arm.startswith("MLMvsCLM/") != pretraining:
                continue
            interval = (
                f"[{fmt(cell['effect_one_sd_ci_low'], 3)}, "
                f"{fmt(cell['effect_one_sd_ci_high'], 3)}]"
            )
            rows.append(
                " & ".join(
                    [
                        _LABELS[arm],
                        f"{fmt(cell['effect_one_sd'], 3)} {interval}",
                        fmt(cell["partial_r2"], 3),
                        fmt(cell["geometry_spearman_vs_canonical_w2"], 3),
                    ]
                )
                + r" \\"
            )
        if not pretraining:
            rows.append(r"\midrule")
    caption = (
        "Supplementary lexical and pretraining comparisons on "
        f"{summary['return_window']} returns, using {summary['n_firms']} firms "
        f"and {summary['n_dyads']:,} dyads. All rows use symmetric additive firm "
        "effects and the same "
        f"{summary['bootstrap_requested_draws']:,} multinomial node-bootstrap "
        r"draws. $\Delta D$/1 SD is the fitted change in return chord distance "
        "per full-sample dyadic standard deviation of each distance, with its "
        r"pointwise percentile 95\% interval. Partial $R^2$ measures the "
        "reduction in residual sum of squares relative to firm effects alone. "
        r"Rank agreement is Spearman correlation with canonical Qwen $W_2$. "
        "These supplementary comparisons are separate from the paired-contrast "
        "families reported above."
    )
    table = _render_longtable(
        rows,
        columns="lrrr",
        header=(
            r"Representation & $\Delta D$/1 SD [95\% CI] & Partial $R^2$ "
            r"& Rank agreement \\"
        ),
        caption=caption,
        label="tab:text-controls",
        font_size="small",
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "text_controls.tex").write_text(
        "% AUTO-GENERATED by pipeline render-paper1-text-controls.\n" + table + "\n",
        encoding="utf-8",
    )
